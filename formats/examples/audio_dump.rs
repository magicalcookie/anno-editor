// Decodes what an audio asset plays and writes each clip to a 16-bit .wav,
// to check the Wwise decode by ear or by its numbers: prints the event's
// tree, then per clip its length and peak and RMS level.
//
//   cargo run -p anno-formats --release --example audio_dump -- [<guid>] [<out dir>]
//
// The default is 51235 (`evt_fba_resident_sweeping`, the broom a resident
// sweeps with in a sequence), written to anno-audio/ in the system's temp
// folder.

use std::io::Write;

use anno_formats::audio::{self, Library, Media, Node, NodeId};
use anno_formats::vfs::{Install, install_dir};
use anyhow::{Context, Result};

fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let guid: u32 = args.first().map_or(Ok(51235), |g| g.parse())?;
    let out = args.get(1).map_or_else(
        || std::env::temp_dir().join("anno-audio"),
        std::path::PathBuf::from,
    );
    let dir = install_dir("ANNO117_DIR").context("set ANNO117_DIR")?;
    let install = Install::open(dir, &["data"])?;
    let t = std::time::Instant::now();
    let lib = Library::load(&install, "en_us")?;
    println!("library loaded in {:.0?}", t.elapsed());

    let e = lib.event(guid).context("not an Audio asset")?;
    println!(
        "{guid}: Wwise event {}, heard to {}",
        e.wwise_id, e.max_attenuation
    );
    let mut clips = Vec::new();
    for &root in e.roots {
        tree(&lib, root, 1, &mut clips);
    }
    let mut picked = Vec::new();
    lib.pick(guid, |n| n / 2, &mut picked);
    println!(
        "pick (middle choices): {:?}",
        picked.iter().map(|m| m.id).collect::<Vec<_>>()
    );

    std::fs::create_dir_all(&out)?;
    for m in clips {
        let mut pcm = Vec::new();
        let f = audio::decode(&lib.read(&install, m)?, &mut pcm)?;
        let peak = pcm.iter().fold(0f32, |a, s| a.max(s.abs()));
        let rms = (pcm.iter().map(|s| s * s).sum::<f32>() / pcm.len().max(1) as f32).sqrt();
        let path = out.join(format!("{guid}_{}.wav", m.id));
        write_wav(&path, f.sample_rate, f.channels, &pcm)?;
        println!(
            "{}: {} Hz x{}{}, {} frames = {:.0} ms, peak {:.1} dBFS, RMS {:.1} dBFS",
            path.display(),
            f.sample_rate,
            f.channels,
            if f.ambisonic { " ambisonic" } else { "" },
            f.frames,
            f.frames as f64 * 1000. / f.sample_rate as f64,
            20. * peak.max(1e-9).log10(),
            20. * rms.max(1e-9).log10(),
        );
    }
    Ok(())
}

fn tree(lib: &Library, id: NodeId, depth: usize, clips: &mut Vec<Media>) {
    let pad = "  ".repeat(depth);
    let (label, kids): (String, &[NodeId]) = match lib.node(id) {
        Node::Media(m) => {
            clips.push(m);
            (format!("media {}", m.id), &[])
        }
        Node::Missing(id) => (format!("missing media {id}"), &[]),
        Node::Generated(p) => (format!("generated by plugin {p:#010x}"), &[]),
        Node::Random(c) => ("random".into(), c),
        Node::Sequence {
            children,
            continuous,
        } => (format!("sequence (continuous: {continuous})"), children),
        Node::Switch(c) => ("switch".into(), c),
        Node::Layer(c) => ("layer".into(), c),
    };
    println!("{pad}{label}");
    for &k in kids {
        tree(lib, k, depth + 1, clips);
    }
}

fn write_wav(path: &std::path::Path, rate: u32, channels: u16, pcm: &[f32]) -> Result<()> {
    let data = (pcm.len() * 2) as u32;
    let mut w = std::io::BufWriter::new(std::fs::File::create(path)?);
    w.write_all(b"RIFF")?;
    w.write_all(&(36 + data).to_le_bytes())?;
    w.write_all(b"WAVEfmt ")?;
    w.write_all(&16u32.to_le_bytes())?;
    w.write_all(&1u16.to_le_bytes())?;
    w.write_all(&channels.to_le_bytes())?;
    w.write_all(&rate.to_le_bytes())?;
    w.write_all(&(rate * channels as u32 * 2).to_le_bytes())?;
    w.write_all(&(channels * 2).to_le_bytes())?;
    w.write_all(&16u16.to_le_bytes())?;
    w.write_all(b"data")?;
    w.write_all(&data.to_le_bytes())?;
    for s in pcm {
        w.write_all(&((s.clamp(-1., 1.) * 32767.) as i16).to_le_bytes())?;
    }
    Ok(())
}
